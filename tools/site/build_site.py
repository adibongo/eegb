"""build_site.py — generates the Quarto website source (home, datasets, one page per session)
from tools/sessions.json + tools/site/content.json (exported from the slide decks).
Hand-written pages (setup, about, pre-module, intra-module, assessment) are not touched.
Run:  node tools/site/export_content.js && python3 tools/site/build_site.py && quarto render
"""
import json, os, glob, re
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
os.chdir(ROOT)
S = json.load(open("tools/sessions.json"))
C = json.load(open("tools/site/content.json"))
REPO = "https://github.com/adibongo/eegb"
NS = len(S)
PARTS = {1: ("Part I", "Microeconomics & the Market System", "assets/logos/eegb_hex_p1_256.png"),
         2: ("Part II", "Macroeconomics, Policy & Risk", "assets/logos/eegb_hex_p2_256.png"),
         3: ("Part III", "Open-Economy Macro, Trade & Geoeconomics", "assets/logos/eegb_hex_p3_256.png"),
         4: ("Part IV", "Strategic Frontiers: Climate, Risk & Corporate Macro Strategy", "assets/logos/eegb_hex_p4_256.png")}


def deck_file(s, ext="pptx"):
    f = glob.glob(f"sessions/{s['slug']}/slides/*.{ext}")
    return os.path.basename(f[0]) if f else None


def esc(t): return (t or "").replace("|", "\\|")
def yq(t): return (t or "").replace('"', "'")


def scripts(slug):
    rs = {os.path.splitext(os.path.basename(f))[0]: f for f in glob.glob(f"sessions/{slug}/R/*.R")}
    ps = {os.path.splitext(os.path.basename(f))[0]: f for f in glob.glob(f"sessions/{slug}/python/*.py")}
    stems = sorted(set(rs) | set(ps), key=lambda x: (0 if "figures" in x else 1, x))
    return [(st, rs.get(st), ps.get(st)) for st in stems]


def label(stem):
    st = re.sub(r"^s\d\d_", "", stem)
    if st == "figures": return "Replicate every chart"
    if st == "lab": return "Lab"
    return st.replace("_", " ").capitalize()


def code_block(path, lang):
    src = open(path, encoding="utf-8").read().rstrip()
    fence = "````" if "```" in src else "```"
    n = src.count("\n") + 1
    return (f"::: {{.callout-note collapse=\"true\" appearance=\"simple\" icon=false}}\n## Show the full script ({n} lines)\n\n"
            f"{fence}{{.{lang} filename=\"{path}\"}}\n{src}\n{fence}\n:::\n")


def session_page(s):
    slug, n = s["slug"], s["num"]; c = C.get(slug, {}); part = PARTS[s["part"]]
    rel = "../../"
    pptx, pdf = deck_file(s), deck_file(s, "pdf")
    prev = next((x for x in S if x["num"] == n - 1), None); nxt = next((x for x in S if x["num"] == n + 1), None)
    L = [f"---\ntitle: \"Session {n}: {yq(s['title'])}\"\nsubtitle: \"{part[0]} · {part[1]}\"\n"
         f"description: \"{yq(s['focus'])}\"\nimage: {rel}{part[2]}\n---\n"]
    L.append(f"::: {{.session-banner}}\n![]({rel}{part[2]}){{.banner-hex width=\"96\"}}\n\n")
    L.append(f"**Session {n} of {NS}** · Facilitator: {s['facilitator']}" + (f"<br>*Case:* {s['case']}" if s.get("case") else "") + "\n\n:::\n\n")
    L.append("## Downloads {.unnumbered}\n\n::: {.download-row}\n")
    if pptx: L.append(f"[<i class=\"bi bi-file-earmark-slides\"></i> Teaching slides (.pptx)]({rel}sessions/{slug}/slides/{pptx}){{.btn .btn-primary download=\"\"}}\n")
    if pdf: L.append(f"[<i class=\"bi bi-file-earmark-pdf\"></i> Slides (PDF)]({rel}sessions/{slug}/slides/{pdf}){{.btn .btn-outline-primary download=\"\"}}\n")
    L.append(f"[<i class=\"bi bi-github\"></i> Session folder on GitHub]({REPO}/tree/main/sessions/{slug}){{.btn .btn-outline-secondary}}\n:::\n\n")
    if s.get("readings"):
        L.append("## Read first {.unnumbered}\n\n" + "".join(f"- **{t}** — {d}\n" for t, d in s["readings"]) + "\n")
    else:
        L.append(f"## Coverage {{.unnumbered}}\n\n{s['source']}\n\n")
    if c.get("objectives"):
        L.append("## Learning objectives\n\n::: {.grid}\n")
        for o in c["objectives"]:
            L.append(f"::: {{.g-col-12 .g-col-md-4 .obj-card}}\n**{o['title']}**\n\n{o['body']}\n:::\n")
        L.append(":::\n\n")
    if c.get("case"):
        k = c["case"]
        L.append(f"## The business case\n\n::: {{.callout-note appearance=\"simple\" icon=false}}\n## {k['title']}\n\n"
                 f"**Situation.** {k['context']}\n\n**Question.** {k['question']}\n\n**Data.** {k['data']}\n\n**A good answer.** {k['decision']}\n:::\n\n")
    if c.get("concepts"):
        L.append("## Key ideas in plain English\n\n")
        for k in c["concepts"]:
            L.append(f"### {k['title']}\n\n{k['plain']}\n\n")
            if k.get("formula"): L.append(f"::: {{.formula}}\n{k['formula']}\n:::\n\n")
            if k.get("example"): L.append(f"*Example.* {k['example']}\n\n")
            if k.get("why"): L.append(f"::: {{.callout-tip appearance=\"minimal\"}}\n**Why a manager cares.** {k['why']}\n:::\n\n")
    if c.get("figures"):
        L.append("## Charts and how to replicate them\n\nEvery chart below is regenerated by the session's figure script — "
                 f"`sessions/{slug}/R/{slug}_figures.R` or `sessions/{slug}/python/{slug}_figures.py`. Run it from the project root.\n\n")
        for f in c["figures"]:
            img = f["img"]; rimg = img.replace("/python/", "/r/")
            L.append(f"### {f['title']}\n\n::: {{.panel-tabset group=\"lang\"}}\n## Python\n![]({rel}{img}){{.fig-img fig-alt=\"{f['id']} (Python)\"}}\n\n")
            if os.path.exists(rimg): L.append(f"## R\n![]({rel}{rimg}){{.fig-img fig-alt=\"{f['id']} (R)\"}}\n\n")
            L.append(":::\n\n")
            if f["points"]: L.append("\n".join(f"- {p}" for p in f["points"]) + "\n\n")
            L.append(f"<span class=\"fig-id\">{f['id']}</span>\n\n")
    if c.get("lab"):
        lb = c["lab"]
        files = [d.strip() for d in lb["data"].split("\n") if d.strip().startswith("data/")]
        L.append(f"## {lb['title']}\n\n*Time:* {lb['time']}" + (" · *Data:* " + ", ".join(f"[`{d}`]({rel}{d})" for d in files) if files else "") + "\n\n")
        L.append("\n".join(f"{i}. {st}" for i, st in enumerate(lb["steps"], 1)) + "\n\n")
        L.append(f"::: {{.callout-important appearance=\"simple\"}}\n**Deliverable:** {lb['deliver']}\n:::\n\n")
    sc = scripts(slug)
    if sc:
        L.append("## The code (R | Python)\n\nPick your language once; every tab on the site follows your choice. "
                 "Download a script, or copy it into RStudio and run it line by line.\n\n")
        for stem, r, p in sc:
            L.append(f"### {label(stem)}\n\n::: {{.panel-tabset group=\"lang\"}}\n")
            if p: L.append(f"## Python\n[<i class=\"bi bi-download\"></i> {os.path.basename(p)}]({rel}{p}){{download=\"\"}}\n\n" + code_block(p, "python") + "\n")
            if r: L.append(f"## R\n[<i class=\"bi bi-download\"></i> {os.path.basename(r)}]({rel}{r}){{download=\"\"}}\n\n" + code_block(r, "r") + "\n")
            L.append(":::\n\n")
    if c.get("checks"):
        L.append("## Check your understanding\n\n")
        for i, q in enumerate(c["checks"], 1):
            L.append(f"**Q{i}.** {q['q']}\n\n" + "\n".join(f"- **{'ABCD'[j]}.** {o}" for j, o in enumerate(q["options"])) + "\n\n")
            L.append(f"::: {{.callout-tip collapse=\"true\" appearance=\"simple\"}}\n## Show answer\n**{'ABCD'[q['answer']]}.** {q['explain']}\n:::\n\n")
    if c.get("glossary"):
        L.append("## Vocabulary\n\n| Term | Meaning |\n|---|---|\n" + "\n".join(f"| **{esc(g['term'])}** | {esc(g['def'])} |" for g in c["glossary"]) + "\n\n")
    if c.get("recap"):
        r = c["recap"]
        L.append("## Key takeaways\n\n" + "\n".join(f"{i}. {it}" for i, it in enumerate(r["items"], 1)) + "\n\n")
        if r.get("prework"): L.append(f"::: {{.callout-note appearance=\"simple\"}}\n**Before next session:** {r['prework']}\n:::\n\n")
    L.append("::: {.session-nav}\n")
    if prev: L.append(f"[← Session {prev['num']}: {prev['short']}]({rel}sessions/{prev['slug']}/index.qmd)\n")
    else: L.append(f"[← Pre-module]({rel}pre-module.qmd)\n")
    if nxt: L.append(f"[Session {nxt['num']}: {nxt['short']} →]({rel}sessions/{nxt['slug']}/index.qmd){{.next}}\n")
    L.append(":::\n")
    open(f"sessions/{slug}/index.qmd", "w", encoding="utf-8").write("".join(L))


for s in S: session_page(s)

